const ALT = [["бл", "б"], ["пл", "п"], ["вл", "в"], ["мл", "м"], ["фл", "ф"], ["ж", "д"], ["ж", "з"], ["ш", "с"], ["ч", "т"], ["ч", "к"], ["щ", "ст"], ["щ", "ск"]];

// Может ли форма с окончанием e быть от глагола с основой s и концом инфинитива i?
// Отсекает начальные формы, которые есть в словаре, но к этой форме не подходят:
// «воду» — не «водить» (было бы «вожу»), «купи» — не «купать» (было бы «купай»),
// «несет» — не «несить» (на -ить спрягаются через «-ит», а не «-ет»).
// alt — основа уже с чередованием («хож-у» → «ход-»): для неё ограничений нет.
const CONJ2 = new Set(["и", "ишь", "ит", "им", "ите", "ат", "ят"]); // второе спряжение и повелительное на -и
const CONJ1 = new Set(["ешь", "ет", "ем", "ете", "ут", "ют"]);
function infFits(s, alt, e, i) {
  if (alt || /[аеиоуыэюя]$/.test(s)) return true;
  const hush = /[жшчщ]$/.test(s), vowelless = !/[аеиоуыэюя]/.test(s); // «держ-и» → «держать», «сп-ишь» → «спать»
  if (CONJ2.has(e)) {
    if (i === "ать" || i === "ять") return hush || vowelless;
    const imp = e === "и" || e === "ите";
    if (i === "уть") return imp && s.endsWith("н"); // «ткни» → «ткнуть», «тянись» → «тянуться»
    if (i === "ти" || i === "чь") return imp; // «неси(те)» → «нести», но «несит» не бывает
    return true;
  }
  if (CONJ1.has(e)) return i !== "ить";
  if (e === "у" || e === "ю") {
    // в 1-м лице у глаголов на -ить согласная меняется: «вожу», «прошу», «люблю» — без чередования не бывает
    if (i === "ить") return !/[дтзсбпвмф]$/.test(s);
    if (i === "ать") return hush || vowelless;
    if (i === "ять") return false;
  }
  return true;
}

function verbStems(stem) {
  const out = [stem];
  for (const [a, b] of ALT) if (stem.endsWith(a) && stem.length > a.length + 1) out.push(stem.slice(0, -a.length) + b);
  return out;
}

// Возможные начальные формы по правилам (без проверки по словарю).
// Возвращает группы: из каждой группы берётся первая форма, которая есть в словаре
// («маму» → «мама», а не ещё и «маме»; «братом» → «брат», а не «брать»).
// Порядок групп: формы, которые бывают только у глаголов («делаешь», «делал») → существительные
// и прилагательные → двусмысленные окончания глаголов («воду» — скорее «вода», чем «водить»).
const VERB_ONLY = ["ешь", "ишь", "ете", "ют", "ут", "ят", "ет", "ит", "ат"];
const VERB_MAYBE = ["ите", "ем", "им", "у", "ю", "и"]; // «и» — повелительное: «позвони» → «позвонить», «напиши» → «написать»
function groupsRu(w) {
  const sure = [], nouns = [], maybe = [];
  const ok = (c) => c && c !== w && c.length >= 2;
  const verbGroup = (v, e, suffix) => {
    if (!v.endsWith(e) || v.length - e.length < 2) return null;
    const g = [];
    const base = v.slice(0, -e.length);
    for (const s of verbStems(base)) {
      if (/[аеиоуыэюя]$/.test(s)) g.push(s + "ть" + suffix); // «зна-ет» → «знать»
      if (s.endsWith("у")) g.push(s.slice(0, -1) + "овать" + suffix); // «рису-ет» → «рисовать»
      if (s.endsWith("ю")) g.push(s.slice(0, -1) + "евать" + suffix);
      for (const i of INF) if (infFits(s, s !== base, e, i)) g.push(s + i + suffix);
    }
    return g.filter(ok);
  };
  const verb = (v, suffix = "") => {
    // прошедшее время: «делал(а/о/и)» → «делать»
    for (const e of ["ла", "ло", "ли", "л"]) {
      if (v.endsWith(e) && v.length - e.length >= 2) { sure.push([v.slice(0, -e.length) + "ть" + suffix].filter(ok)); break; }
    }
    // повелительное: «делай(те)» → «делать»
    // и «бойся» → «бояться», «стой» → «стоять», «волнуйся» → «волноваться», «рисуй» → «рисовать»
    for (const e of ["йте", "й"]) {
      if (!v.endsWith(e) || v.length - e.length < 2) continue;
      const b = v.slice(0, -e.length);
      sure.push([b + "ть" + suffix, ...(/[ое]$/.test(b) ? [b + "ять" + suffix] : []), ...(b.endsWith("у") ? [b.slice(0, -1) + "овать" + suffix] : []), ...(b.endsWith("ю") ? [b.slice(0, -1) + "евать" + suffix] : [])].filter(ok));
    }
    // повелительное на «-ей»: «налей» → «налить» (после существительных: «ночей» — скорее «ночь»)
    for (const e of ["ейте", "ей"]) if (v.endsWith(e) && v.length - e.length >= 2) { maybe.push([v.slice(0, -e.length) + "ить" + suffix].filter(ok)); break; }
    for (const e of VERB_ONLY) { const g = verbGroup(v, e, suffix); if (g) sure.push(g); }
    for (const e of VERB_MAYBE) { const g = verbGroup(v, e, suffix); if (g) (/[аеуя]ю$/.test(v) || suffix ? sure : maybe).push(g); }
  };
  if (/(ся|сь)$/.test(w) && w.length > 4) { verb(w.slice(0, -2), "ся"); verb(w.slice(0, -2)); }
  verb(w);
  for (const e of NOUN_ENDS) {
    if (!w.endsWith(e) || w.length - e.length < 2) continue;
    const stem = w.slice(0, -e.length);
    // «красивая», «красивого» — сначала прилагательное («красивый»), потом остальное
    let order = ADJ_ENDS.has(e) ? ["ый", "ий", "ой", ...NOM] : NOM;
    // «-и» после твёрдой согласной у слова без окончания не бывает: «враги», «ножи» — да, «приходи», «спроси» — нет
    // (это повелительное «приходить», «спросить», а не «приход», «спрос»)
    // «-ю», «-я» у слова без окончания тоже не бывает: «смотрю» — не «смотр» (было бы «смотру»)
    if ((e === "и" && !/[гкхжчшщ]$/.test(stem)) || e === "ю" || e === "я") order = order.filter((n) => n !== "");
    nouns.push(order.map((n) => stem + n).filter(ok));
  }
  nouns.push(["а", "я", "о", "е", "ь"].map((n) => w + n)); // «мам» → «мама», «дел» → «дело»
  // краткие прилагательные и причастия: «сыт» → «сытый», «голоден» → «голодный», «спокоен» → «спокойный»,
  // «удивлен» → «удивленный»
  nouns.push([w + "ый", w + "ий", w + "ой", w + "ный", w.replace(/оен$/, "ойный"), w.replace(/ен$/, "ный")].filter(ok));
  return [...sure, ...nouns, ...maybe];
}
