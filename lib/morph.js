const ADJ_ENDS = new Set(["ого", "его", "ому", "ему", "ыми", "ими", "ая", "яя", "ое", "ее", "ые", "ие", "ым", "им", "ых", "их", "ую", "юю"]);
const NOM = ["", "а", "я", "о", "е", "ь", "й", "ий", "ый", "ой", "ая", "ое", "ие", "ия", "ье", "ья", "ы", "и"];
// чередования в основе глагола: «любл-ю» → «люб-ить», «хож-у» → «ход-ить», «пиш-у» → «пис-ать»
const ALT = [["бл", "б"], ["пл", "п"], ["вл", "в"], ["мл", "м"], ["фл", "ф"], ["ж", "д"], ["ж", "з"], ["ш", "с"], ["ч", "т"], ["ч", "к"], ["щ", "ст"], ["щ", "ск"]];

function verbStems(stem) {
  const out = [stem];
  for (const [a, b] of ALT) if (stem.endsWith(a) && stem.length > a.length + 1) out.push(stem.slice(0, -a.length) + b);
  return out;
}

// Возможные начальные формы по правилам (без проверки по словарю).
// Возвращает группы: из каждой группы берётся первая форма, которая есть в словаре
// («маму» → «мама», а не ещё и «маме»; «братом» → «брат», а не «брать»).
// Порядок групп: формы, которые бывают только у глаголов («делаешь», «делал») → существительные
// и прилагательные → двусмысленные окончания глаголов («воду» — скорее «вода», чем «водить»).
const VERB_ONLY = ["ешь", "ишь", "ете", "ют", "ут", "ят", "ет", "ит", "ат"];
const VERB_MAYBE = ["ите", "ем", "им", "у", "ю", "и"]; // «и» — повелительное: «позвони» → «позвонить», «напиши» → «написать»
function groupsRu(w) {
  const sure = [], nouns = [], maybe = [];
  const ok = (c) => c && c !== w && c.length >= 2;
  const verbGroup = (v, e, suffix) => {
    if (!v.endsWith(e) || v.length - e.length < 2) return null;
    const g = [];
    for (const s of verbStems(v.slice(0, -e.length))) {
      if (/[аеиоуыэюя]$/.test(s)) g.push(s + "ть" + suffix); // «зна-ет» → «знать»
      if (s.endsWith("у")) g.push(s.slice(0, -1) + "овать" + suffix); // «рису-ет» → «рисовать»
      if (s.endsWith("ю")) g.push(s.slice(0, -1) + "евать" + suffix);
      for (const i of INF) g.push(s + i + suffix);
    }
    return g.filter(ok);
  };
  const verb = (v, suffix = "") => {
    // прошедшее время: «делал(а/о/и)» → «делать»
    for (const e of ["ла", "ло", "ли", "л"]) {
      if (v.endsWith(e) && v.length - e.length >= 2) { sure.push([v.slice(0, -e.length) + "ть" + suffix].filter(ok)); break; }
    }
    // повелительное: «делай(те)» → «делать»
    for (const e of ["йте", "й"]) if (v.endsWith(e) && v.length - e.length >= 2) sure.push([v.slice(0, -e.length) + "ть" + suffix].filter(ok));
    // повелительное на «-ей»: «налей» → «налить» (после существительных: «ночей» — скорее «ночь»)
    for (const e of ["ейте", "ей"]) if (v.endsWith(e) && v.length - e.length >= 2) { maybe.push([v.slice(0, -e.length) + "ить" + suffix].filter(ok)); break; }
    for (const e of VERB_ONLY) { const g = verbGroup(v, e, suffix); if (g) sure.push(g); }
    for (const e of VERB_MAYBE) { const g = verbGroup(v, e, suffix); if (g) (/[аеуя]ю$/.test(v) || suffix ? sure : maybe).push(g); }
  };
  if (/(ся|сь)$/.test(w) && w.length > 4) { verb(w.slice(0, -2), "ся"); verb(w.slice(0, -2)); }
  verb(w);
  for (const e of NOUN_ENDS) {
    if (!w.endsWith(e) || w.length - e.length < 2) continue;
    const stem = w.slice(0, -e.length);
    // «красивая», «красивого» — сначала прилагательное («красивый»), потом остальное
    const order = ADJ_ENDS.has(e) ? ["ый", "ий", "ой", ...NOM] : NOM;
    nouns.push(order.map((n) => stem + n).filter(ok));
  }
  nouns.push(["а", "я", "о", "е", "ь"].map((n) => w + n)); // «мам» → «мама», «дел» → «дело»
  // краткие прилагательные и причастия: «сыт» → «сытый», «голоден» → «голодный», «спокоен» → «спокойный»,
  // «удивлен» → «удивленный»
  nouns.push([w + "ый", w + "ий", w + "ой", w + "ный", w.replace(/оен$/, "ойный"), w.replace(/ен$/, "ный")].filter(ok));
  return [...sure, ...nouns, ...maybe];
}
const candidatesRu = (w) => [...new Set(groupsRu(w).flat())];

// ---------- ингушский ----------
const PREVERBS = ["хьал", "хьа", "дӏа", "чу", "тӏа", "ӏо", "ара", "юха", "тӏехь", "кӏал", "хьалха", "тӏера", "чура"];
const IOT = { "е": "де", "я": "да", "ю": "ду", "ё": "до" };
function classSwap(w) {
  if (w.length < 3) return [];
  const out = [];
  if ("вйб".includes(w[0]) && /[аеиоуэюяь]/.test(w[1])) out.push("д" + w.slice(1));
  if (IOT[w[0]]) out.push(IOT[w[0]] + w.slice(1));
  return out;
}
// Окончания падежей, множественного числа и глагольных форм — от длинных к коротким.
// «нанас», «нанаца», «нанага» → «нана»; «ваха», «вахар» → «даха». Отрезанное слово принимается,
// только если такое слово есть в словаре, поэтому лишние варианты ничего не портят.
const INH_ENDS = [
  "ашкахь", "ашкара", "ашца", "ашта", "ашка", "ашна", "ийца", "ийга", "ийна",
  "ахьа", "ахь", "аца", "ера", "ара", "ига", "ана", "ена", "чох", "чоа",
  "ах", "аш", "ий", "ал", "ас", "ус", "ца", "га", "на", "ча", "нна", "ар", "ир", "ад", "ац", "аз", "ой",
  "ш", "с", "е", "о", "и", "а", "ь", "й",
];
const INH_TAIL = ["", "а", "и", "е", "о", "ий"];
function stripInh(w) {
  const out = [];
  for (const e of INH_ENDS) {
    if (!w.endsWith(e) || w.length - e.length < 2) continue;
    const stem = w.slice(0, -e.length);
    for (const t of INH_TAIL) { const c = stem + t; if (c !== w && c.length >= 2) out.push(c); }
  }
  return out;
}
function candidatesInh(w, strip = true) {
  const out = classSwap(w);
  for (const p of PREVERBS) {
    if (w.startsWith(p) && w.length > p.length + 2) for (const c of classSwap(w.slice(p.length))) out.push(p + c);
  }
  // показатель класса меняем и у слова без окончания: «вахар» → «вах-» → «дах-» → «даха»
  if (strip) for (const c of stripInh(w)) { out.push(c); out.push(...classSwap(c)); }
  return out;
}

// has(lang, word) → есть ли такое слово в словаре. Возвращает функции с памятью.
module.exports = function makeMorph(has) {
  const memo = { ru: new Map(), inh: new Map(), inhShallow: new Map() };
  // Начальные формы слова, которые есть в словаре (не больше max). Само слово сюда не входит.
  // strip = false — для ингушского только показатель класса, без отрезания окончаний
  function lemmas(word, lang, max = 3, strip = true) {
    const w = stripStress(String(word || "")).toLowerCase().replace(/ё/g, "е").replace(/Ӏ/g, "ӏ");
    if (w.length < 2) return [];
    const m = memo[lang === "inh" ? (strip ? "inh" : "inhShallow") : "ru"];
    const hit = m.get(w);
    if (hit) return hit.slice(0, max);
    const out = [];
    const take = (c) => { if (c !== w && !out.includes(c) && has(lang, c)) out.push(c); };
    if (lang === "inh") { for (const c of candidatesInh(w, strip)) { if (out.length >= 4) break; take(c); } }
    else {
      for (const c of IRREGULAR.get(w) || []) take(c);
      if (w.length >= 3) {
        for (const g of groupsRu(w)) {
          if (out.length >= 4) break;
          const c = g.find((x) => x !== w && has(lang, x));
          if (c && !out.includes(c)) out.push(c);
        }
      }
    }
    if (m.size > 50000) m.clear();
    m.set(w, out);
    return out.slice(0, max);
  }
  return { lemmas };
};
module.exports.stripStress = stripStress;
module.exports.candidatesRu = candidatesRu;
module.exports.candidatesInh = candidatesInh;
module.exports.IRREGULAR = IRREGULAR;
