// Окончания падежей, множественного числа и глагольных форм — от длинных к коротким.
// «нанас», «нанаца», «нанага» → «нана»; «ваха», «вахар» → «даха». Отрезанное слово принимается,
// только если такое слово есть в словаре, поэтому лишние варианты ничего не портят.
const INH_ENDS = [
  "ашкахь", "ашкара", "ашца", "ашта", "ашка", "ашна", "ийца", "ийга", "ийна",
  "лахь", // вежливое повелительное: «хьажалахь» → «хьажа» (только после основы на -а/-е)
  "ахьа", "ахь", "аца", "ера", "ара", "ига", "ана", "ена", "чох", "чоа",
  "ах", "ех", "аш", "ий", "ал", "ас", "ус", "ца", "га", "на", "ча", "ега", "ехь", "нна", "ар", "ир", "ад", "ац", "аз", "ой",
  "ш", "с", "е", "о", "и", "а", "ь", "й",
];
const CASE_ENDS = new Set(["ашца", "аца", "ца", "ас", "с", "ех", "ашка", "ега", "ига", "га", "ах", "ара", "ера", "нна", "ашна", "ана", "ена"]);
const INH_TAIL = ["", "а", "и", "е", "о", "ий"];
// → [[начальная форма, отрезанное окончание]]
function stripInh(w, deep = false) {
  const out = [];
  for (const e of INH_ENDS) {
    if (!w.endsWith(e) || w.length - e.length < 2) continue;
    const stem = w.slice(0, -e.length);
    if (e === "лахь" && (!deep || stem.length < 3 || !/[ае]$/.test(stem))) continue; // «лелахь», «гӏолахь» — не повелительное
    for (const t of INH_TAIL) { const c = stem + t; if (c !== w && c.length >= 2) out.push([c, e]); }
  }
  return out;
}
// Окончания падежей, перед которыми гласная основы меняется: «ненаца», «нанега» (lib/ingush-guide.js, раздел 6)
const ABLAUT_ENDS = new Set(["аца", "ца", "ега", "ах", "ал", "ара", "ера"]);
// Гласная основы в косвенных падежах меняется. Обратно: «аь» → «а» («наьна» → «нана», «хаьттача» → «хатта»);
// у слова без окончания — только это. Для отрезанного: конечное «е» основы → «а» («ахчеи» → «ахча»),
// а после окончаний падежа и первое «е» → «а» («ненаца» → «нана»). Берётся, только если такое слово есть в словаре.
function ablaut(c, caseEnd) {
  const out = [];
  if (c.includes("аь")) out.push(c.replace("аь", "а"));
  if (caseEnd === undefined) return out;
  if (c.length > 2 && c.endsWith("е")) out.push(c.slice(0, -1) + "а");
  const i = c.indexOf("е");
  if (i > 0 && ABLAUT_ENDS.has(caseEnd)) out.push(c.slice(0, i) + "а" + c.slice(i + 1));
  return out;
}
// deep — ещё и разбор поглубже (связка на конце, «-лахь», чередование гласной). Он находит больше слов,
// но даёт словарную форму («вахав» → «ваха» — уйти), а не ту, что в тексте; поэтому он для подсказки
// к отдельному слову и разбора по словам, а не для перевода предложения по кускам.
function candidatesInh(w, strip = true, deep = false) {
  const out = classSwap(w);
  for (const p of PREVERBS) {
    if (w.startsWith(p) && w.length > p.length + 2) for (const c of classSwap(w.slice(p.length))) out.push(p + c);
  }
  if (!strip) return out;
  // показатель класса меняем и у слова без окончания: «вахар» → «вах-» → «дах-» → «даха»
  const stripped = stripInh(w, deep);
  // после окончаний падежа существительного сначала основы без замены класса: «вошаца» → «воша» (брат),
  // а не «дош» (слово); у глагольных окончаний — как раньше («вахар» → «дах-»)
  for (const [c, e] of stripped) { out.push(c); if (!CASE_ENDS.has(e)) out.push(...classSwap(c)); }
  for (const [c, e] of stripped) if (CASE_ENDS.has(e)) out.push(...classSwap(c));
  if (!deep) return out;
  // связка, приросшая к слову: «миштав» = «мишта ва», «вахав» = «ваха ва». Только целое слово на -а
  // (от 4 букв), без дальнейших отрезаний: «хиннад» — не «хин» (водяной), «даьд» — не «даь», «диад» — не «диа»
  if (w.length >= 5 && /[^ь]а[вбд]$/.test(w)) { const b = w.slice(0, -1); out.push(b, ...classSwap(b)); }
  // чередование гласной — в последнюю очередь
  for (const c of [w, ...out]) out.push(...ablaut(c));
  for (const [c, e] of stripped) for (const a of ablaut(c, e)) { out.push(a); out.push(...classSwap(a)); }
  return out;
}

// has(lang, word) → есть ли такое слово в словаре. Возвращает функции с памятью.
module.exports = function makeMorph(has) {
  const memo = { ru: new Map(), inh: new Map(), inhShallow: new Map(), inhDeep: new Map() };
  // Начальные формы слова, которые есть в словаре (не больше max). Само слово сюда не входит.
  // strip = false — для ингушского только показатель класса, без отрезания окончаний;
  // deep = true — для ингушского ещё и разбор поглубже (см. candidatesInh)
  function lemmas(word, lang, max = 3, strip = true, deep = false) {
    const w = stripStress(String(word || "")).toLowerCase().replace(/ё/g, "е").replace(/Ӏ/g, "ӏ");
    if (w.length < 2) return [];
    deep = deep && strip;
    const m = memo[lang === "inh" ? (deep ? "inhDeep" : strip ? "inh" : "inhShallow") : "ru"];
    const hit = m.get(w);
    if (hit) return hit.slice(0, max);
    const out = [];
    const take = (c) => { if (c !== w && !out.includes(c) && has(lang, c)) out.push(c); };
    if (lang === "inh") { for (const c of candidatesInh(w, strip, deep)) { if (out.length >= 4) break; take(c); } }
    else {
      for (const c of IRREGULAR.get(w) || []) take(c);
      if (w.length >= 3) {
        for (const g of groupsRu(w)) {
          if (out.length >= 4) break;
          // «приходи» не может быть формой «приходы»: окончание -и вместо -ы пишется только после г, к, х, ж, ч, ш, щ
          const c = g.find((x) => x !== w && has(lang, x) && !(/и$/.test(w) && x === w.slice(0, -1) + "ы"));
          if (c && !out.includes(c)) out.push(c);
        }
      }
    }
    if (m.size > 50000) m.clear();
    m.set(w, out);
    return out.slice(0, max);
  }
  return { lemmas };
};
module.exports.stripStress = stripStress;
module.exports.candidatesRu = candidatesRu;
module.exports.candidatesInh = candidatesInh;
module.exports.IRREGULAR = IRREGULAR;
