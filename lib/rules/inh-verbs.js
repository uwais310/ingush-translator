// Разбор ингушских форм глагола для перевода «по кускам» с ингушского (lib/rules/chunks.js).
// Только узнаёт форму во входном тексте и находит словарный глагол — ингушских слов не создаёт.
// Каждый образец формы взят из источника:
//   будущее: основа + «-рг-» + класс, с отрицанием ещё «-ц» (lib/rules/verbs.js, PaydaDosh): «Со кхоана
//     воагӀаргва» (я приеду завтра), «Аз эцаргда из» (я куплю это), «ХӀама дергдац» (ничего страшного),
//     «хургва», «аргда», «гӀоргвац»;
//   перфект: причастие + класс, с отрицанием ещё «-ац» (PaydaDosh): «Фу хиннад?» (что случилось?), «Цунах
//     хьехархо хиннав» (он стал учителем), «хиннай» (она стала), «Со цӀаккхаза хиннавац цига» (я никогда там
//     не был), «Хьо волча хиннавар со» (был); причастие — прошедшее время из словаря проекта без «-р»
//     («дахар» — шёл → «дахад»);
//   повелительное: словарная форма на -а/-е + «-л» или вежливое «-лахь» (справочник, раздел 7: Хьажалахь,
//     Алалахь; PaydaDosh: «дувца, дувцалахь, дувцал — расскажи…», «КӀеззига сабардел» — подожди немного,
//     «Сона укхаз сабарделахь» — подожди меня здесь, «Юха алал» — повтори ещё раз);
//   отрицание настоящего: форма настоящего времени + «-ц» / «-ац» (справочник: хов → хац; библиотека слов:
//     кхета → кхетац).
//
//   const A = makeInhVerbs({ finOf, sensesOf, isPerfective });
//   A.analyze("дергдац") → { inf: "сделать", tense: "fut", neg: true, cls: "д", how: "fut" }

const low = (s) => String(s).toLowerCase().replace(/ё/g, "е").replace(/Ӏ/g, "ӏ").replace(/[̀́]/g, "");

// Неправильные основы будущего (lib/rules/verbs.js, IRREGULAR; все формы — из PaydaDosh)
const FUT_IRR = { "ху": "быть", "а": "сказать", "гӏо": "пойти" };
// «приходить»: воагӀа, йоагӀа, доагӀа, боагӀа (справочник, раздел 4): «Со кхоана воагӀаргва» — я приеду завтра
const COMES = new Set(["воагӏа", "йоагӏа", "доагӏа", "боагӏа"]);
// «хила» (быть): причастие «хинна» — «Фу хиннад?», «хиннав», «хиннай», «хиннаб» (PaydaDosh)
const PART_IRR = { "хинна": "быть" };
// окончание будущего по классу (lib/rules/verbs.js): в — -ва, й — -ья/-ъя/-я, д — -да, б — -ба
const FUT_RE = /^(.+?)рг(ва|ья|ъя|я|да|ба)(ц)?$/;
const FUT_CLS = { "ва": "в", "ья": "й", "ъя": "й", "я": "й", "да": "д", "ба": "б" };

// Будущее в ингушском вида не различает; в разговорнике по-русски чаще совершенный вид: «ховргда» — узнает,
// «гургда вай» — увидимся, «эцаргда» — куплю. Пары видов — правило русского языка, ингушского здесь нет.
const PERF = { "знать": "узнать", "видеть": "увидеть", "слышать": "услышать", "делать": "сделать", "читать": "прочитать",
  "писать": "написать", "покупать": "купить", "брать": "взять", "давать": "дать", "приходить": "прийти", "понимать": "понять",
  "пить": "выпить", "ждать": "подождать", "рассказывать": "рассказать", "спрашивать": "спросить", "открывать": "открыть",
  "закрывать": "закрыть", "находить": "найти", "забывать": "забыть", "отвечать": "ответить", "учить": "выучить" };

function classSwap(w) {
  const out = [];
  if ("вйб".includes(w[0]) && /[аеиоуэюяь]/.test(w[1] || "")) out.push("д" + w.slice(1));
  const IOT = { "е": "де", "я": "да", "ю": "ду" };
  if (IOT[w[0]]) out.push(IOT[w[0]] + w.slice(1));
  return out;
}

// finOf(форма) → { inf, tense: "pres"|"past", cls } — форма из словаря проекта или библиотеки слов;
// sensesOf(ингушская словарная форма) → [русские инфинитивы] из надёжных словарей (первый — главный);
// isPerfective(русский инфинитив) → совершенный ли вид (для будущего: «сделаю», а не «буду делать»)
module.exports = function makeInhVerbs({ finOf, sensesOf, isPerfective }) {
  // русский глагол для ингушской основы: сама основа или она же с показателем класса д
  function verbOf(stem, preferPerf) {
    for (const c of [stem, ...classSwap(stem)]) {
      const s = sensesOf(c);
      // сначала надёжные пары видов (PERF), потом общий признак совершенного вида
      if (s && s.length) return (preferPerf && (PERF[s[0]] || s.find((x) => PERF_VALUES.has(x)) || s.find((x) => isPerfective(x)))) || s[0];
    }
    return null;
  }

  function future(w) {
    const m = FUT_RE.exec(w);
    if (!m) return null;
    const P = m[1], cls = FUT_CLS[m[2]], neg = !!m[3];
    let inf = FUT_IRR[P] || (COMES.has(P) ? "прийти" : null);
    if (!inf && P.length >= 2) {
      inf = verbOf(P, true);
      // основа настоящего времени на согласный + «-арг-»: «лох» → «лохаргда» (lib/rules/verbs.js)
      if (!inf && /а$/.test(P) && P.length >= 4) { const f = finOf(P.slice(0, -1)); if (f && f.tense === "pres") inf = f.inf; }
      if (!inf) { const f = finOf(P); if (f && f.tense === "pres") inf = f.inf; }
    }
    return inf ? { inf, tense: "fut", neg, cls, how: "fut" } : null;
  }

  // перфект: причастие + класс («хиннад», «дахад»), с отрицанием «-ац», давнопрошедшее «-ар» («хиннавар»)
  // класс й перед «-ац», «-ар» пишется «я»: «хиннаяц» = хинна + й + ац (PaydaDosh: «Ца яьчох нана хиннаяц» —
  // не рожавшая матерью не стала, «Цхьан кхерах гӀала хиннаяц» — из одного камня не построишь башни)
  function perfect(w) {
    let m = /^(.{2,}[аеиоуэюяь])([вйдб])(ац|ар)?$/.exec(w);
    const y = !m && /^(.{2,}[аеиоуэь])я([цр])$/.exec(w);
    if (y) m = [w, y[1], "й", "а" + y[2]];
    if (!m) return null;
    const part = m[1], cls = m[2], neg = m[3] === "ац";
    if (PART_IRR[part]) return { inf: PART_IRR[part], tense: "past", neg, cls, how: "perfect" };
    for (const c of [part, ...classSwap(part)]) {
      const f = finOf(c + "р");
      if (f && f.tense === "past") return { inf: f.inf, tense: "past", neg, cls, how: "perfect" };
    }
    return null;
  }

  // повелительное: «сабардел», «сабарделахь», «алал», «хьажалахь»
  // «-л» без «-ахь» — только в конце предложения (так во всех примерах); иначе это скорее «-ал» сравнения:
  // «дешал» — чем слово, «сагал» — чем человек (справочник, раздел 6)
  function imperative(w, last = true) {
    const m = /^(.{2,}[ае])(лахь|л)$/.exec(w);
    if (!m || (m[2] === "л" && !last)) return null;
    const inf = verbOf(m[1], true); // «дувцал» — расскажи (PaydaDosh): совершенный вид, если он есть
    return inf ? { inf, tense: "imp", neg: false, cls: null, how: "imper", polite: m[2] === "лахь" } : null;
  }

  // отрицание настоящего: «кхетац», «дувцац»
  function presNeg(w) {
    const m = /^(.{2,}?)(ац|ц)$/.exec(w);
    if (!m) return null;
    // «дуац» — не ест: настоящее «дуъ» (словарь проекта) без «ъ»
    for (const c of m[2] === "ц" ? [m[1]] : [m[1] + "ъ", m[1], m[1] + "а"]) {
      if (m[2] === "ц" && !/[аеиоуя]$/.test(c)) continue;
      const f = finOf(c);
      if (f && f.tense === "pres") return { ...f, tense: "pres", neg: true, how: "presneg" };
    }
    return null;
  }

  // strong — формы с надёжным признаком (будущее «-рг-», вежливое «-лахь»): им веришь больше словаря;
  // остальные — только если словарь не знает слова или знает лишь его «начальную форму» по догадке
  function analyze(w, { last = true } = {}) {
    const x = low(w);
    if (x.length < 4) return null;
    const f = future(x);
    if (f) return { ...f, strong: true };
    if (/лахь$/.test(x)) { const i = imperative(x); if (i) return { ...i, strong: true }; }
    return perfect(x) || imperative(x, last) || presNeg(x);
  }

  return { analyze, future, perfect, imperative, presNeg };
};
const PERF_VALUES = new Set(Object.values(PERF));
module.exports.PERF = PERF;
