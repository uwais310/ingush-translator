const POSS_NOM = {};
for (const [k, v] of Object.entries({ "мой": "моя мое мои", "твой": "твоя твое твои", "свой": "своя свое свои", "наш": "наша наше наши", "ваш": "ваша ваше ваши", "этот": "эта это эти", "тот": "та то те" })) {
  const [f, n, pl] = v.split(" ");
  POSS_NOM[k] = k; POSS_NOM[f] = k; POSS_NOM[n] = k; POSS_NOM[pl] = k;
}
function poss(word, g, kase, anim = false) {
  const lem = POSS_NOM[low(word)];
  if (!lem) return ["его", "ее", "их"].includes(low(word)) ? low(word) : null;
  if (kase === "nom" || (kase === "acc" && g !== "f" && (!anim || g === "n"))) return R.poss(lem, g, "nom") || null;
  const P = POSS[lem];
  const I = { gen: 0, dat: 1, ins: 2, prep: 3, acc: 0 };
  if (g === "f") return kase === "acc" ? P.f[4] : P.f[I[kase]];
  return (g === "pl" ? P.pl : P.m)[I[kase]];
}

// Предлог перед словом: «со мной», «во время», «ко мне», «об отце»
function prep(p, next) {
  const n = low(next || "");
  if (p === "с" && /^[сзшж][бвгджзклмнпрстфхцчшщ]/.test(n)) return "со";
  if (p === "в" && /^[вф][бвгджзклмнпрстфхцчшщ]/.test(n)) return "во";
  if (p === "к" && /^(мн|вс)/.test(n)) return "ко";
  if (p === "о" && /^[аиоуэ]/.test(n)) return "об";
  return p;
}

