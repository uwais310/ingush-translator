const HUSH = /[гкхжшщч]$/; // после них — «и», а не «ы»
const SIB = /[жшщчц]$/; // после них безударное «ей», «ем»

// Существительное word (начальная форма) в падеже kase. { loc2: true } — после «в / на» («в лесу»).
function noun(word, kase, opts = {}) {
  const orig = String(word);
  const cap = /^[А-ЯЁ]/.test(orig);
  const w = low(orig);
  if (!w || /\s/.test(w) || !kase) return null;
  const done = (f) => (f == null ? null : cap ? f[0].toUpperCase() + f.slice(1) : f);
  if (kase === "nom") return done(w);
  const irr = IRR[w];
  if (irr && irr.fixed) return done(w);
  if (irr && irr[kase]) return done(irr[kase]);
  if (kase === "prep" && opts.loc2 && LOC2[w]) return done(LOC2[w]);
  const g = gender(w);
  if (!g || g === "pl") return null;
  const anim = animate(w);
  if (kase === "acc") {
    if (/[ая]$/.test(w) && g !== "n") return done(w.slice(0, -1) + (/я$/.test(w) ? "ю" : "у"));
    if (g === "m" && anim) return noun(orig, "gen");
    return done(w);
  }
  // 1-е склонение: мама, папа, неделя, линия
  if (/[ая]$/.test(w) && !/мя$/.test(w)) {
    const st = w.slice(0, -1), soft = /я$/.test(w), iya = /ия$/.test(w);
    const F = {
      gen: iya || soft || HUSH.test(st) ? st + "и" : st + "ы",
      dat: iya ? st + "и" : st + "е",
      ins: soft ? st + "ей" : SIB.test(st) ? st + "ей" : st + "ой",
      prep: iya ? st + "и" : st + "е",
    };
    return done(F[kase]);
  }
  // 3-е склонение: ночь, тетрадь, Назрань
  if (/ь$/.test(w) && g === "f") {
    const st = w.slice(0, -1);
    return done({ gen: st + "и", dat: st + "и", ins: st + "ью", prep: st + "и" }[kase]);
  }
  // 2-е склонение: средний род на -о / -е
  if (g === "n" && /[ое]$/.test(w)) {
    // «сердце», «солнце», «жилище» — после ц/ж/ш/щ/ч окончания твёрдые: сердца, сердцу, но сердцем
    const st = w.slice(0, -1), sib = /[цжшщч]е$/.test(w), soft = /е$/.test(w) && !sib, ie = /ие$/.test(w);
    const F = {
      gen: soft ? st + "я" : st + "а",
      dat: soft ? st + "ю" : st + "у",
      ins: soft || sib ? st + "ем" : st + "ом",
      prep: ie ? st + "и" : st + "е",
    };
    return done(F[kase]);
  }
  // 2-е склонение: мужской род — брат, отец, конь, музей, санаторий
  if (g === "m") {
    let st = w, soft = false, ii = false;
    if (/ь$/.test(w)) { st = w.slice(0, -1); soft = true; }
    else if (/й$/.test(w)) { st = w.slice(0, -1); soft = true; ii = /ий$/.test(w); }
    else if (/[ауоыэюяеи]$/.test(w)) return null; // «папа» выше; прочее — несклоняемое или неясное
    if (FLEET[w] === null) { /* без беглой гласной */ } else if (FLEET[w]) st = FLEET[w];
    else if (irr && irr.stem) st = irr.stem;
    const F = {
      gen: soft ? st + "я" : st + "а",
      dat: soft ? st + "ю" : st + "у",
      ins: soft || (/ц$/.test(st) && !ENDSTRESS.has(w)) ? st + "ем" : st + "ом",
      prep: ii ? st + "и" : st + "е",
    };
    return done(F[kase]);
  }
  return null;
}

// Прилагательное (начальная форма на -ый / -ий / -ой) в роде g и падеже kase; anim — для винительного
function adj(lemma, g, kase, anim = false) {
  const w = low(lemma);
  const m = /^(.*)(ый|ий|ой)$/.exec(w);
  if (!m || !g) return null;
  if (kase === "nom" || (kase === "acc" && g !== "f" && (!anim || g === "n"))) return R.adj(w, g, "nom");
  const [, st, end] = m;
  const hush = HUSH.test(st), sib = /[жшщч]$/.test(st);
  const soft = end === "ий" && !hush; // синий
  const e = (hard, sft) => st + (soft ? sft : hard);
  const yi = soft || hush ? "и" : "ы";
  const o = soft || (sib && end !== "ой") ? "е" : "о";
  if (g === "f") return { gen: st + o + "й", dat: st + o + "й", acc: soft ? st + "юю" : st + "ую", ins: st + o + "й", prep: st + o + "й" }[kase] || null;
  if (g === "pl") return { gen: st + yi + "х", dat: st + yi + "м", acc: st + yi + "х", ins: st + yi + "ми", prep: st + yi + "х" }[kase] || null;
  const F = { gen: e(o === "е" ? "его" : "ого", "его"), dat: e(o === "е" ? "ему" : "ому", "ему"), acc: e(o === "е" ? "его" : "ого", "его"), ins: st + yi + "м", prep: st + o + "м" };
  return F[kase] || null;
}

