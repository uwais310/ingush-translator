// приставки, после которых особый глагол спрягается так же («на-писать», «у-видеть», «при-йти»)
const PREFIXES = ["", "по", "при", "у", "в", "во", "вы", "за", "на", "о", "об", "обо", "от", "ото", "пере", "под", "подо", "про", "с", "со",
  "раз", "разо", "рас", "расс", "до", "из", "изо", "вз", "взо", "вс", "недо", "пре", "вос", "воз", "съ", "объ", "подъ", "отъ", "разъ", "въ", "при", "переи"];
const ANY_PREFIX = new Set(["ереть"]);

function findIrr(v) {
  if (IRR[v]) return { key: v, pre: "", e: IRR[v] };
  let best = null;
  for (const key of Object.keys(IRR)) {
    if (!v.endsWith(key) || v === key) continue;
    const pre = v.slice(0, -key.length);
    if (!ANY_PREFIX.has(key) && !PREFIXES.includes(pre)) continue;
    if (!best || key.length > best.key.length) best = { key, pre, e: IRR[key] };
  }
  return best;
}

const HUSH = /[жшчщ]$/;
function first(sg1, st) { return [sg1, st + "ешь", st + "ет", st + "ем", st + "ете", sg1 + "т"]; }
function second(sg1, st) { return [sg1, st + "ишь", st + "ит", st + "им", st + "ите", st + (HUSH.test(st) ? "ат" : "ят")]; }
// 1-е лицо 2-го спряжения: ходить → хожу, просить → прошу, любить → люблю, чистить → чищу
function sg1Second(st) {
  let s = st;
  if (/ст$/.test(s)) s = s.slice(0, -2) + "щ";
  else if (/[дз]$/.test(s)) s = s.slice(0, -1) + "ж";
  else if (/с$/.test(s)) s = s.slice(0, -1) + "ш";
  else if (/т$/.test(s)) s = s.slice(0, -1) + "ч";
  else if (/[бпвфм]$/.test(s)) s += "л";
  return s + (HUSH.test(s) ? "у" : "ю");
}

// Шесть форм настоящего времени (без -ся) или null
function presentForms(v) {
  const irr = findIrr(v);
  if (irr) {
    const [p] = irr.e;
    let forms;
    if (p.includes(" ")) forms = p.split(" ");
    else {
      const [sg1, st, conj] = p.split("|");
      forms = conj === "2" ? second(sg1, st) : first(sg1, st);
    }
    let pre = irr.pre;
    // при-йти → приду (не «прийду»), съ-есть → съем
    if (irr.key === "йти" && /и$/.test(pre)) return forms.map((f) => pre + f.slice(1));
    return forms.map((f) => pre + f);
  }
  let m;
  if ((m = /^(.+)([цжшч])евать$/.exec(v))) return first(m[1] + m[2] + "ую", m[1] + m[2] + "у");
  if ((m = /^(.+)овать$/.exec(v))) return first(m[1] + "ую", m[1] + "у"); // рисовать → рисую
  if ((m = /^(.+[аеоу])ять$/.exec(v))) return first(m[1] + "ю", m[1]); // лаять → лаю, сеять → сею
  if ((m = /^(.+[ая])ть$/.exec(v))) return first(m[1] + "ю", m[1]); // делать → делаю, гулять → гуляю
  if ((m = /^(.+е)ть$/.exec(v))) return first(m[1] + "ю", m[1]); // уметь → умею
  if ((m = /^(.+)нуть$/.exec(v))) return first(m[1] + "ну", m[1] + "н"); // вернуть → верну
  if ((m = /^(.+)уть$/.exec(v))) return null;
  if ((m = /^(.+)оть$/.exec(v))) return first(m[1] + "ю", m[1]); // колоть → колю, колешь
  if ((m = /^(.+)ить$/.exec(v))) { const st = m[1]; if (st.length < 2) return null; return second(sg1Second(st), st); }
  return null;
}

// Возвратный глагол: «учиться» → «учить» + ся
function splitRefl(inf) {
  const v = String(inf || "").toLowerCase().replace(/ё/g, "е").trim();
  if (/(ться|тись|чься)$/.test(v)) return { v: v.slice(0, -2), refl: true };
  return { v, refl: false };
}
const addRefl = (f) => (/[аеиоуыэюя]$/.test(f) ? f + "сь" : f + "ся");

function present(inf, person) {
  const { v, refl } = splitRefl(inf);
  if (!/(ть|ти|чь)$/.test(v) || person == null || person < 0 || person > 5) return null;
  // «бояться»: в таблице 1-е лицо уже с -сь
  if (findIrr(v) && findIrr(v).key === "боять") { const f = presentForms(v)[person]; return f.endsWith("сь") ? f : addRefl(f); }
  const forms = presentForms(v);
  if (!forms) return null;
  return refl ? addRefl(forms[person]) : forms[person];
}

function past(inf, g = "m") {
  const { v, refl } = splitRefl(inf);
  const i = { m: 0, f: 1, n: 2, pl: 3 }[g];
  if (i == null || !/(ть|ти|чь)$/.test(v)) return null;
  const irr = findIrr(v);
  let forms = null;
  if (irr && irr.e[1]) {
    const [m, st] = irr.e[1].split("|");
    let pre = irr.pre;
    if (irr.key === "йти" && pre === "от") pre = "ото"; // отойти → отошел
    forms = [pre + m, pre + st + "а", pre + st + "о", pre + st + "и"];
  } else if (/ть$/.test(v)) {
    const st = v.slice(0, -2);
    forms = [st + "л", st + "ла", st + "ло", st + "ли"];
  }
  if (!forms) return null;
  return refl ? addRefl(forms[i]) : forms[i];
}

const isInfinitive = (w) => /(ть|ти|чь|ться|тись|чься)$/.test(String(w || "").toLowerCase());

// Повелительное наклонение (ты): «сказать» → «скажи», «подождать» → «подожди», «делать» → «делай», «учиться» → «учись».
// Правило: основа 3-го лица мн. числа + «и»; после гласной — «й» (делают → делай). Ударение по написанию
// не видно, поэтому глаголы с безударным окончанием («встань», «брось», «плачь») — списком. Не знаем — null.
const IMP_IRR = { "дать": "дай", "есть": "ешь", "пить": "пей", "лить": "лей", "бить": "бей", "шить": "шей", "лечь": "ляг",
  "сесть": "сядь", "стать": "стань", "встать": "встань", "быть": "будь", "ехать": "езжай", "идти": "иди", "йти": "йди",
  "бросить": "брось", "готовить": "готовь", "ответить": "ответь", "ставить": "ставь", "оставить": "оставь", "поставить": "поставь",
  "забыть": "забудь", "плакать": "плачь", "резать": "режь", "верить": "верь", "тратить": "трать", "жарить": "жарь",
  "петь": "пой", "мыть": "мой", "крыть": "крой", "смеять": "смейся", "бояться": "бойся" };
function imperative(inf) {
  const { v, refl } = splitRefl(inf);
  if (!/(ть|ти|чь)$/.test(v)) return null;
  const R = (f) => (refl ? addRefl(f) : f);
  if (IMP_IRR[v]) return R(IMP_IRR[v]);
  for (const k of Object.keys(IMP_IRR)) {
    const pre = v.slice(0, -k.length);
    if (v.endsWith(k) && v !== k && PREFIXES.includes(pre)) return R(/^(при|у|по|за|на|вы|пере|до|от|ото|про|под|об|обо|в|во|вз|раз|со|с|из|изо)$/.test(pre) && k === "йти" ? (pre === "при" ? "приди" : pre + "йди") : pre + IMP_IRR[k]);
  }
  if (/авать$/.test(v)) return R(v.slice(0, -2) + "й"); // давать → давай, вставать → вставай
  const forms = presentForms(v);
  if (!forms) return null;
  const sg1 = forms[0], pl3 = forms[5];
  if (/[аеиоуя]ю$/.test(sg1)) return R(sg1.slice(0, -1) + "й"); // делаю → делай, умею → умей
  const st = pl3.replace(/(ут|ют|ат|ят)$/, "");
  if (st === pl3) return null;
  return R(st + "и");
}

// Будущее время: совершенный вид — простое («скажу»), иначе — «буду» + инфинитив («буду делать»).
function future(inf, person, perfective) {
  if (perfective || /^быть$/.test(String(inf))) return present(inf, person);
  const b = present("быть", person);
  return b && isInfinitive(inf) ? b + " " + inf : null;
}

