// Глаголы для перевода «по кускам» с русского (lib/rules/chunks.js): будущее время, вид глагола,
// переходность. Новых ингушских слов здесь не придумывается: форма по образцу берётся, только если
// ровно такая форма есть в ингушских текстах (lib/ingush-words.js) — иначе правило молчит.
//
// Будущее время в ингушском — основа + «-рг-» + класс того, кто идёт (непереходный глагол) или что
// делают (переходный): «Со кхоана воагӀаргва» (я приеду завтра, мужчина), «Аз эцаргда из» (я куплю это),
// «Аз каьхат яьздергда» (я напишу письмо), «Со хьежаргва шуга» (я буду вас ждать), «Кхоана кино гӀоргда
// вай» (мы пойдём в кино), «КӀаьнк школе гӀоргва» (мальчик пойдёт в школу); с отрицанием -ц на конце:
// «Со гӀоргвац / гӀоргьяц» (я не пойду), «Со хьога хьежаргвац» (не буду тебя ждать). Все примеры — PaydaDosh.
// Справочник: «мегаргда» (можно).
//
//   const V = makeVerbs({ RET });
//   V.isPerfective("сделать") → true   («сделаю» — будущее)
//   V.future(["де"], ["ду"]) → { pos: { д: "дергда" }, neg: { д: "дергдац" } }

const low = (s) => String(s).toLowerCase().replace(/ё/g, "е").replace(/[1lI|Ӏ]/g, "ӏ").replace(/[̀́]/g, "");
let WORDS = null;
const attested = (w) => (WORDS || (WORDS = new Set(require("../ingush-words.js").split("\n")))).has(low(w));

// Окончание будущего по классу: в — -ва, й — -ья (в текстах и -ъя, -я), д — -да, б — -ба
const END = { в: ["ва"], й: ["ья", "ъя", "я"], д: ["да"], б: ["ба"] };
// Неправильные основы будущего — каждая форма есть в разговорнике PaydaDosh:
//   хила (быть): «Со сай ханахьа хургва», «Деррига дика хургда», «хургья диктор», «Довхой дукха хургба»
//   ала (сказать): «аргда аз» (скажу тебе), «хьох дикадар аргдац»
//   даха (пойти): «Со гӀоргвац / гӀоргьяц», «КӀаьнк школе гӀоргва», «Кхоана кино гӀоргда вай», «гӀоргья»
const IRREGULAR = { "хила": "ху", "ала": "а", "даха": "гӀо", "ваха": "гӀо", "яха": "гӀо", "баха": "гӀо" };
// Русские глаголы, у которых будущее берётся от ингушского «даха» (пойти, поехать) и «хила» (быть, стать)
// «приеду, приду» — от «воагӀа, йоагӀа, доагӀа, боагӀа» (справочник, раздел 4: comes): «Со кхоана воагӀаргва»,
// «Маца воагӀаргва хьо?» (PaydaDosh)
const COMES = { в: "воагӀа", й: "йоагӀа", д: "доагӀа", б: "боагӀа" };
const RU_FUT_STEM = { "пойти": "даха", "поехать": "даха", "уйти": "даха", "уехать": "даха", "быть": "хила", "стать": "хила", "прийти": COMES, "приехать": COMES };

// Совершенный вид: «сделаю, напишу, куплю» — это будущее время, а не настоящее.
const PERF_LIST = new Set(["купить", "дать", "взять", "сказать", "показать", "рассказать", "заказать", "решить", "бросить", "лечь", "сесть", "встать",
  "стать", "кончить", "пустить", "прийти", "уйти", "найти", "пойти", "понять", "начать", "забыть", "умереть", "получить", "вернуться", "остаться",
  "помочь", "поймать", "отдохнуть", "проснуться", "вспомнить", "приехать", "уехать", "поехать", "выйти", "войти", "зайти", "перейти", "дойти", "подойти",
  "отдать", "продать", "передать", "сдать", "узнать", "увидеть", "услышать", "простить", "позвать", "съесть", "выпить", "надеть", "снять", "открыть", "закрыть"]);
const PREFIXES = ["пере", "раз", "рас", "под", "про", "при", "вы", "за", "на", "по", "от", "об", "до", "вз", "из", "ис", "с", "у", "в"];
// приставка + «ходить, носить…» или суффикс -ывать / -ивать / -авать — несовершенный вид («приходить», «рассказывать»)
const IMPERF = /(ывать|ивать|авать|евать|ходить|носить|водить|возить|езжать|бегать|летать|плывать|лезать|ниматься|нимать|ступать|бирать|глядывать)(ся)?$/;

// Формы будущего, которые русская морфология (lib/morph.js) не сводит к начальной форме
const RU_IRREGULAR = {};
for (const [lemma, forms] of Object.entries({
  "прийти": ["приду", "придешь", "придет", "придем", "придете", "придут"],
  "пойти": ["пойду", "пойдешь", "пойдет", "пойдем", "пойдете", "пойдут"],
  "уйти": ["уйду", "уйдешь", "уйдет", "уйдем", "уйдете", "уйдут"],
  "найти": ["найду", "найдешь", "найдет", "найдем", "найдете", "найдут"],
  "быть": ["буду", "будешь", "будет", "будем", "будете", "будут"],
})) forms.forEach((f, n) => (RU_IRREGULAR[f] = { lemma, pn: n }));
// лицо и число по окончанию русского глагола: 0 я, 1 ты, 2 он, 3 мы, 4 вы, 5 они
function personOf(w) {
  const x = low(w);
  if (RU_IRREGULAR[x]) return RU_IRREGULAR[x].pn;
  if (/(ешь|ишь)(ся)?$/.test(x)) return 1;
  if (/(ете|ите)(сь)?$/.test(x)) return 4;
  if (/(ем|им)(ся)?$/.test(x)) return 3;
  if (/(ут|ют|ат|ят)(ся)?$/.test(x)) return 5;
  if (/(ет|ит)(ся)?$/.test(x)) return 2;
  if (/[ую](сь)?$/.test(x)) return 0;
  return null;
}

module.exports = function makeVerbs({ RET }) {
  const isVerbLemma = (l) => /(ть|ться|ти|чь|чься)$/.test(l);
  const known = (l) => { const r = RET.lookupWord(l, "ru", 3); return !!(r && !r.lemma && r.items.some((x) => x.prio <= 1)); };
  // глагол без приставки: «написать» → «писать»
  function unprefixed(lemma) {
    for (const p of PREFIXES) {
      if (!lemma.startsWith(p) || lemma.length - p.length < 4) continue;
      const rest = lemma.slice(p.length);
      if (isVerbLemma(rest) && known(rest)) return rest;
    }
    return null;
  }
  function isPerfective(lemma) {
    const l = low(lemma);
    if (PERF_LIST.has(l)) return true;
    if (IMPERF.test(l)) return false;
    if (/нуть(ся)?$/.test(l) && !/^(тонуть|тянуть|гнуть|тянуться)$/.test(l)) return true;
    return !!unprefixed(l);
  }

  // Будущее по основам (словарная форма, настоящее время): { pos: {класс: форма}, neg: {…} } — только
  // формы, которые есть в текстах. stems: строки или { в, й, д, б } (основа по классу: «воагӀа / доагӀа»).
  function future(...stemSets) {
    const pos = {}, neg = {};
    for (const set of stemSets) {
      for (const s of [].concat(set || [])) {
        if (!s) continue;
        const byCls = typeof s === "object" ? s : { в: s, й: s, д: s, б: s };
        for (const [c, raw] of Object.entries(byCls)) {
          if (!raw || !END[c]) continue;
          const words = String(raw).trim().split(/\s+/), last = words.pop();
          const stem = IRREGULAR[low(last)] || last;
          // короткая основа («ва», «ба») — скорее обрывок, чем глагол; кроме неправильных и «де» (делать: дергда)
          if ((low(stem).length < 3 && !IRREGULAR[low(last)] && low(stem) !== "де") || /[^а-яӏ]/i.test(low(stem))) continue;
          const pre = words.length ? words.join(" ") + " " : "";
          const bases = [stem + "рг"];
          if (/[^аеиоуыэюяь]$/i.test(low(stem))) bases.push(stem + "арг"); // «лох» → «лохаргда»
          for (const b of bases) {
            for (const e of END[c]) {
              if (!pos[c] && attested(b + e)) pos[c] = pre + b + e;
              if (!neg[c] && attested(b + e + "ц")) neg[c] = pre + b + e + "ц";
            }
          }
        }
      }
    }
    return Object.keys(pos).length || Object.keys(neg).length ? { pos, neg } : null;
  }

  // Будущее для русского глагола: словарные формы его ингушского перевода (и глагола без приставки:
  // «написать» → «писать» → «язде» → «яздергда»).
  function futureOf(lemma, formsOf) {
    const l = low(lemma);
    // идти, приходить, быть — непереходные (справочник, раздел 4: вода, воагӀа согласуются с тем, кто идёт)
    const intr = (r) => r && Object.assign(r, { intr: true });
    if (RU_FUT_STEM[l]) return intr(future(RU_FUT_STEM[l]));
    const tryL = (x) => { const f = formsOf(x); return f && future(f.inf, f.pres); };
    let r = tryL(l);
    if (r) return r;
    const u = unprefixed(l);
    if (u && RU_FUT_STEM[u]) return intr(future(RU_FUT_STEM[u]));
    return u ? tryL(u) : null;
  }

  return { isPerfective, future, futureOf, unprefixed, attested, personOf, irregular: (w) => RU_IRREGULAR[low(w)] || null };
};
module.exports.attested = attested;
