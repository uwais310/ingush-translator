// Перевод «по кускам» без ИИ (lib/rules/chunks.js) и то, что сервер отвечает им, когда ИИ выключен.
//   node test/chunks.test.js
// Ожидаемые ингушские слова — из справочника (lib/ingush-guide.js) и словаря проекта, не придуманы.
delete process.env.USE_AI;
const assert = require("assert");
const KB = require("../lib/ingush-guide.js");
const LEX = require("../lib/corpus-lexicon.js");
const SEED = require("../data/phrases.json");
const RET = require("../lib/retrieval.js")({ KB, SEED, LEX });
const C = require("../lib/rules/chunks.js")({ RET, SEED });
const tr = (t, src = "ru") => (C.translate(t, src) || {}).translation;

(async () => {
  // 1. глаголы знания — с дательным (справочник: «сона хов»), дополнение в именительном, глагол в конце
  assert.strictEqual(tr("Я знаю этого человека"), "Сона ер саг хов");
  console.log("ok 1: «Я знаю этого человека» →", tr("Я знаю этого человека"));

  // 2. «и» — «а» после каждого слова (справочник: «да а нана а»)
  assert.ok(/^Да а нана а /.test(tr("Отец и мать работают дома")), tr("Отец и мать работают дома"));
  console.log("ok 2: «Отец и мать…» →", tr("Отец и мать работают дома"));

  // 3. «идёт» согласуется с подлежащим: мальчик — в (вода), она — й (йода); предлог «в» не переводится
  assert.ok(/ вода$/.test(tr("Мальчик идёт в школу")), tr("Мальчик идёт в школу"));
  assert.ok(/^Из .* йода$/.test(tr("Она идёт в магазин")), tr("Она идёт в магазин"));
  console.log("ok 3: класс глагола по подлежащему —", tr("Мальчик идёт в школу"), "|", tr("Она идёт в магазин"));

  // 4. «люблю» согласуется с тем, кого любят (справочник: «Сона хьо веза» — мужчине)
  assert.strictEqual(tr("Я тебя люблю"), "Сона хьо веза");
  assert.ok(/нана еза$/.test(tr("Я люблю свою маму")), tr("Я люблю свою маму"));
  console.log("ok 4: «Я тебя люблю» →", tr("Я тебя люблю"), "|", tr("Я люблю свою маму"));

  // 5. ингушский → русский: местоимения, глаголы по лицу, связка в конце не переводится;
  // в русском вопросе вопросительное слово — первым
  assert.strictEqual(tr("Хьо мича вода?", "inh"), "Куда ты идешь?");
  assert.strictEqual(tr("Из кхалсаг я", "inh"), "Она женщина");
  console.log("ok 5: ингушский → русский —", tr("Хьо мича вода?", "inh"), "|", tr("Из кхалсаг я", "inh"));

  // 6. неизвестное слово — в [скобках]; почти ничего не известно — модуль молчит
  assert.ok(/\[[а-я]+\]/.test(tr("Сегодня хорошая погода, мы пойдём на реку")), tr("Сегодня хорошая погода, мы пойдём на реку"));
  assert.strictEqual(C.translate("Квазиэлектрон фрактализуется", "ru"), null);
  console.log("ok 6: неизвестные слова в скобках, бессмыслица — без ответа");

  // 6б. связка, если глагола нет (справочник, раздел 4): «Из дика саг ва»; с «не» — вац; в вопросе — за вопросительным словом
  assert.strictEqual(tr("Он мой брат"), "Из са воша ва");
  assert.strictEqual(tr("Мой брат не дома"), "Са воша цӀагӀа вац");
  assert.strictEqual(tr("Где мой брат?"), "Мичахьа ва са воша?");
  assert.ok(!/ (ва|да)$/.test(tr("Старый друг вернулся")), "«старый друг» — не «друг старый»: связки нет");
  console.log("ok 6б: связка —", tr("Он мой брат"), "|", tr("Мой брат не дома"), "|", tr("Где мой брат?"));

  // 6в. шаблоны разговорника с «…» (PaydaDosh: «Меня зовут … — Со … яхаш ва» / «Са цӀи … я»); имя остаётся как есть
  assert.ok(/Ахмед/.test(tr("Меня зовут Ахмед")) && /(яхаш|цӀи)/.test(tr("Меня зовут Ахмед")), tr("Меня зовут Ахмед"));
  assert.strictEqual(tr("Са цӀи Ахмед я", "inh"), "Меня зовут Ахмед");
  // повелительное наклонение не угадываем: остаётся в скобках
  assert.ok(/\[приходи\]/.test(tr("Приходи завтра")), tr("Приходи завтра"));
  // «Мишта ва хьо?» — связка перед местоимением в русском не нужна
  assert.strictEqual(tr("Мишта ва хьо?", "inh"), "Как ты?");
  console.log("ok 6в: шаблоны и осторожность —", tr("Меня зовут Ахмед"), "|", tr("Приходи завтра"), "|", tr("Мишта ва хьо?", "inh"));

  // 6е. ингушский → русский (справочник, разделы 4–8; PaydaDosh):
  // причастие на -ш + связка — настоящее время глагола по лицу подлежащего; «вац» — «не»
  assert.strictEqual(tr("Со кхеташ вац.", "inh"), "Я не понимаю.");
  assert.ok(/^Он .*живет\.$/.test(tr("Из Назране вахаш ва.", "inh")), tr("Из Назране вахаш ва.", "inh"));
  // глагол второй, подлежащее после него → по-русски подлежащее перед глаголом, вопросительное слово первым
  assert.ok(/^(Где|Куда) ты живешь\?$/.test(tr("Мича вах хьо?", "inh")), tr("Мича вах хьо?", "inh"));
  // прошедшее связки — по подлежащему: «Мича дар шо?» (Where were you?)
  assert.ok(/^(Где|Куда) вы были\?$/.test(tr("Мича дар шо?", "inh")), tr("Мича дар шо?", "inh"));
  // «X а Y а» — «X и Y»
  assert.strictEqual(tr("ди а бийса а", "inh"), "День и ночь");
  // слитная связка: «Миштав хьо?» = «Мишта ва хьо?»
  assert.strictEqual(tr("Миштав хьо?", "inh"), "Как ты?");
  // глагол с дательным: кому — подлежащее, кто в именительном — дополнение («Сона хьо веза» — я тебя люблю)
  assert.strictEqual(tr("Сона хьо веза", "inh"), "Я тебя люблю");
  // «не» связки — перед сказуемым
  assert.strictEqual(tr("Са воша цӀагӀа вац", "inh"), "Мой брат не дома");
  console.log("ok 6е: ингушский → русский —", tr("Со кхеташ вац.", "inh"), "|", tr("Мича вах хьо?", "inh"), "|", tr("ди а бийса а", "inh"), "|", tr("Миштав хьо?", "inh"));

  // 6ж. русское спряжение (lib/rules/ru-conj.js) — только русская грамматика
  const RC = require("../lib/rules/ru-conj.js");
  assert.strictEqual(RC.present("понимать", 0), "понимаю");
  assert.strictEqual(RC.present("ходить", 0), "хожу");
  assert.strictEqual(RC.present("любить", 0), "люблю");
  assert.strictEqual(RC.present("жить", 2), "живет");
  assert.strictEqual(RC.present("учиться", 5), "учатся");
  assert.strictEqual(RC.present("написать", 1), "напишешь");
  assert.strictEqual(RC.present("прийти", 0), "приду");
  assert.strictEqual(RC.present("рисовать", 0), "рисую");
  assert.strictEqual(RC.past("идти", "f"), "шла");
  assert.strictEqual(RC.past("учиться", "m"), "учился");
  assert.strictEqual(RC.past("мочь", "pl"), "могли");
  console.log("ok 6ж: русское спряжение");

  // 6г. таблица фраз из пар разговорника (lib/rules/align.js): «я не знаю» — «сона хац» (PaydaDosh / справочник);
  // каждое слово куска взято из ингушской стороны настоящих пар; редкий кусок (одна пара) не используется
  {
    const ok = (p) => /^(PaydaDosh|Справочник)/.test(p.source || "") && !p.rare; // rare — форм нет в текстах: в таблицу слов не берём
    const pairs = SEED.filter((p) => (p.kind === "phrase" || p.kind === "word") && ok(p)).map((p) => [p.ru, p.inh]).concat(KB.EXAMPLES, KB.GLOSSARY);
    const A = require("../lib/rules/align.js")(pairs);
    const toks = require("../lib/rules/align.js").toks;
    const ap = A.phrase(["я", "не", "знаю"], "ru");
    assert.ok(ap && ap.to === "сона хац" && ap.n >= 2 && ap.p >= 0.3, JSON.stringify(ap));
    const inhWords = new Set(pairs.flatMap(([, i]) => toks(i)));
    assert.ok(ap.to.split(" ").every((w) => inhWords.has(w)));
    assert.strictEqual(A.phrase(["квази", "электрон"], "ru"), null);
    assert.strictEqual(A.phrase(["я", "не", "знаю"], "ru", { minN: 1000 }), null);
    // хук в chunks.js: кусок, которого нет в словаре, берётся из таблицы фраз
    const C2 = require("../lib/rules/chunks.js")({ RET, SEED, ALIGN: { best: () => null, prob: () => 0, phrase: (ws) => (ws.join(" ") === "квази электрон" ? { to: "сона хац", p: 1, n: 9 } : null) } });
    const r = C2.translate("Квази электрон", "ru");
    assert.ok(r && r.pieces.some((x) => x.how === "align-phrase"), JSON.stringify(r));
    console.log("ok 6г: таблица фраз — «я не знаю» →", ap.to, `(p=${ap.p.toFixed(2)}, n=${ap.n})`);
  }
  // 6г. падежи существительных (lib/rules/cases.js). Формы — из справочника, раздел 6:
  // нанега (to mother), нанна (to mother, dative), сагаца (with the man), сагах (about the man), юртара (from the village), сага (of the man)
  const makeCases = require("../lib/rules/cases.js");
  const CS = makeCases({ words: require("../lib/ingush-words.js") });
  assert.strictEqual(CS.form("нана", "all"), "нанега");
  assert.strictEqual(CS.form("нана", "dat"), "нанна");
  assert.strictEqual(CS.form("саг", "ins"), "сагаца");
  assert.strictEqual(CS.form("саг", "abl"), "сагах");
  assert.strictEqual(CS.form("юрт", "from"), "юртара");
  assert.strictEqual(CS.form("саг", "gen"), "сага");
  assert.strictEqual(CS.form("квазиэлектрон", "dat"), null, "формы нет в текстах — null");
  // падеж русского слова — по предлогу и окончанию
  const ctx = (s, k, l) => CS.context(s.split(" "), k, l, () => true);
  assert.strictEqual(ctx("к маме", 1, "мама"), "all");
  assert.strictEqual(ctx("позвони маме", 1, "мама"), "dat");
  assert.strictEqual(ctx("с братом", 1, "брат"), "ins");
  assert.strictEqual(ctx("о матери", 1, "мать"), "abl");
  assert.strictEqual(ctx("из села", 1, "село"), "from");
  assert.strictEqual(ctx("дом человека", 1, "человек"), "gen");
  // в предложении: «Я иду к маме» — направительный, «дом человека» — родительный перед существительным
  assert.ok(/нанега/.test(tr("Я иду к маме")), tr("Я иду к маме"));
  assert.ok(/^Сага цӀа/.test(tr("Дом человека")), tr("Дом человека"));
  assert.ok(/сагаца/.test(tr("Я говорю с человеком")), tr("Я говорю с человеком"));
  console.log("ok 6г: падежи —", tr("Я иду к маме"), "|", tr("Дом человека"), "|", tr("Я говорю с человеком"));

  // 6д. будущее время (lib/rules/verbs.js): основа + -рг- + класс; только формы, что есть в текстах.
  // Образцы — разговорник PaydaDosh: «Я приеду завтра → Со кхоана воагӀаргва», «Я не пойду → Со гӀоргвац»,
  // «Я куплю это → Аз эцаргда из», «Я напишу письмо → Аз каьхат яьздергда», «Я буду вас ждать → Со хьежаргва
  // шуга», «Мальчик пойдет в школу → КӀаьнк школе гӀоргва», «Когда придёшь? → Маца воагӀаргва хьо?»,
  // «все будет хорошо → деррига дика хургда»
  assert.strictEqual(tr("Я приеду завтра"), "Со кхоана воагӀаргва");
  assert.strictEqual(tr("Я не пойду"), "Со гӀоргвац");
  assert.ok(/^Аз .*эцаргда$/.test(tr("Я куплю это")), tr("Я куплю это"));
  assert.ok(/^Аз .*дергда$/.test(tr("Я напишу письмо")), tr("Я напишу письмо"));
  assert.ok(/^Со .*хьежаргва$/.test(tr("Я буду вас ждать")), tr("Я буду вас ждать"));
  assert.ok(/ гӀоргва$/.test(tr("Мальчик пойдёт в школу")), tr("Мальчик пойдёт в школу"));
  assert.ok(/воагӀаргва/.test(tr("Когда придёшь?")) && /хьо/.test(tr("Когда придёшь?")), tr("Когда придёшь?"));
  assert.ok(/дика хургда$/.test(tr("Всё будет хорошо")), tr("Всё будет хорошо"));
  // прошедшее «пришёл» — открытый вопрос (CLAUDE.md): не переводим
  assert.ok(!/(вера|хьавенав)/.test(tr("Мальчик пришёл домой") || ""), tr("Мальчик пришёл домой"));
  console.log("ok 6д: будущее —", tr("Я приеду завтра"), "|", tr("Я не пойду"), "|", tr("Я куплю это"), "|", tr("Когда придёшь?"));

  // 6е. отрицание из библиотеки слов (справочник: «Сона хац»; PaydaDosh: «Со кхетац») и «жить» —
  // причастие со связкой в утверждении (PaydaDosh: «Из Назране вахаш ва»), простая форма в вопросе («Мича вах хьо?»)
  assert.strictEqual(tr("Я не знаю"), "Сона хац");
  assert.strictEqual(tr("Я не понимаю"), "Со кхетац");
  assert.ok(/вахаш ва$/.test(tr("Он живёт в Назрани")), tr("Он живёт в Назрани"));
  assert.ok(/ вах/.test(tr("Где ты живёшь?")) && !/вахаш/.test(tr("Где ты живёшь?")), tr("Где ты живёшь?"));
  console.log("ok 6е: отрицание и «вахаш ва» —", tr("Я не знаю"), "|", tr("Я не понимаю"), "|", tr("Он живёт в Назрани"));

  // 6ж. повелительное и прошедшее (PaydaDosh: «позвать — деха», «убрать — дӀадаха»; справочник: идти —
  // прош. вахар/яхар; «принести — ба / да»: класс по предмету, вода — д: «Хий дӀайха да»);
  // «работать — болх бе» → будущее «болх бергба» (форма есть в текстах); «пусть будет» — хилда («Ди дика хилда хьа!»)
  assert.ok(/ деха$/.test(tr("Позови отца")), tr("Позови отца"));
  assert.ok(!/\[/.test(tr("Убери посуду")), tr("Убери посуду"));
  // в вопросе глагол сразу за вопросительным словом (справочник, раздел 7: «Фу аьлар Ӏа?», «Мича дар шо?»)
  assert.strictEqual(tr("Куда он пошёл?"), "Мича вахар из?");
  assert.ok(/^Хий да$/.test(tr("Принеси воду")), tr("Принеси воду"));
  assert.ok(/болх бергба$/.test(tr("Она будет работать")), tr("Она будет работать"));
  assert.ok(/хилда/.test(tr("Пусть день будет хорошим")), tr("Пусть день будет хорошим"));
  console.log("ok 6ж: повелительное, прошедшее, «пусть» —", tr("Позови отца"), "|", tr("Куда он пошёл?"), "|", tr("Принеси воду"), "|", tr("Пусть день будет хорошим"));

  // 6з. выбор значения слова (lib/rules/sense.js): из нескольких записей словаря — та, что подтверждают
  // тексты, пары фраз и часть речи. Ожидания — из словаря проекта (lib/ingush-guide.js, GLOSSARY) и PaydaDosh:
  // «мать — нана», «ребёнок — бер (мн. бераш)», «стол — истол / шу (низкий столик)», «обед — делкъийга хӀама».
  {
    const ok = (p) => /^(PaydaDosh|Справочник)/.test(p.source || "") && !p.rare; // rare — форм нет в текстах: в таблицу слов не берём
    const phr = SEED.filter((p) => p.kind === "phrase" && ok(p)).map((p) => [p.ru, p.inh]).concat(KB.EXAMPLES);
    const wrd = SEED.filter((p) => p.kind === "word" && ok(p)).map((p) => [p.ru, p.inh]).concat(KB.GLOSSARY);
    const A = require("../lib/rules/align.js")([...phr, ...wrd]);
    const C3 = require("../lib/rules/chunks.js")({ RET, SEED, ALIGN: A, EXAMPLES: phr });
    const t3 = (t) => (C3.translate(t, "ru") || {}).translation || "";
    // «матери» — форма слова «мать» (словарь проекта: нана), а не «матёрый — гила» (PaydaDosh)
    for (const f of [tr, t3]) assert.ok(/^(Нана|Наьна|Нанна|Нанега|Наьнага)/.test(f("Скажи матери")) && !/гила/i.test(f("Скажи матери")), f("Скажи матери"));
    // «детей» — множественное: «бераш» (словарь проекта: «бер (д/д; мн. бераш)»; PaydaDosh: «дети — бераш»)
    for (const f of [tr, t3]) assert.ok(/^Бераш /.test(f("Позови детей")), f("Позови детей"));
    assert.ok(/^Бераш /.test(t3("Отвези детей в школу")), t3("Отвези детей в школу"));
    // а «книгу» — единственное: «книжка», не «книжкаш»
    assert.ok(/книжка/i.test(t3("Возьми книгу")) && !/книжкаш/i.test(t3("Возьми книгу")), t3("Возьми книгу"));
    // «стол» — «истол» (первое значение словаря проекта; в текстах «стол — истол, истола»), не «шу» (низкий столик)
    assert.ok(/ истол /.test(t3("Положи еду на стол")) && !/ шу /.test(t3("Положи еду на стол")), t3("Положи еду на стол"));
    // «обед» — запись «делкъийга хӀама», а не её кусок «делкъийга» (в полдень) и не описание из трёх слов
    assert.ok(/делкъийга хӀама/.test(t3("Она варит обед")) && !/дуа/.test(t3("Она варит обед")), t3("Она варит обед"));
    // «интересный»: запись «Интересный — Земе» (другой словарь внутри PaydaDosh, с заглавной) не берётся;
    // выбирается одно из значений словарей: куцах дола (PaydaDosh), сакъердаме, безаме (Викисловарь)
    for (const t of ["Я читаю интересную книгу", "Это интересный фильм"]) {
      assert.ok(!/земе/i.test(t3(t)) && /(куцах дола|сакъердаме|безаме)/.test(t3(t)), t3(t));
    }
    // «вечером» — обстоятельство, не дополнение: подлежащее «мы» при «отдыхать» — «тхо» (справочник, раздел 3)
    assert.ok(/ тхо /.test(t3("Вечером мы отдыхаем")), t3("Вечером мы отдыхаем"));
    // очки видны для отладки; без выбора (tune.noSense) — как раньше: первая запись
    assert.ok(C3.explainSense("матери").length >= 2);
    const C0 = require("../lib/rules/chunks.js")({ RET, SEED, ALIGN: A, EXAMPLES: phr, tune: { noSense: true } });
    assert.ok(/гила/i.test((C0.translate("Скажи матери", "ru") || {}).translation), "без выбора значения — старое поведение");
    console.log("ok 6з: выбор значения —", t3("Скажи матери"), "|", t3("Позови детей"), "|", t3("Положи еду на стол"), "|", t3("Я читаю интересную книгу"));

    // 6и. согласование по классу и порядок слов (справочник, разделы 3–8; PaydaDosh)
    // «любить» — с дательным (раздел 5: «сона деза»; раздел 6: дательный «нанна»), глагол согласуется с тем, кого
    // любят: «бер (д/д; мн. бераш)» — класс мн. ч. д (PaydaDosh: «Са ши бер да», «Тха бераш дац») → «деза»
    assert.strictEqual(t3("Мать любит детей"), "Нанна бераш деза");
    assert.strictEqual(t3("Мама любит дочь"), "Нанна йоӀ еза"); // «Сона хьо еза» (о женщине)
    // «отцу — даьна» (корпус GhalghayTools); «даьга» (направительный) — не дательный
    assert.ok(/^Даьна воӀ веза$/.test(t3("Отец любит сына")), t3("Отец любит сына"));
    // «добрая» — «добрый — дика» (справочник), а не «добрая, радостная весть — кхаъ» (PaydaDosh)
    assert.strictEqual(t3("Она добрая женщина"), "Из дика кхалсаг я");
    // «как» в вопросе — «мишта» (раздел 3; «Как вы живёте? — Мишта дах шо?»), вопрос: слово, глагол, кто
    assert.strictEqual(t3("Как вы живёте?"), "Мишта дах шо?");
    assert.strictEqual(t3("Как ты живёшь?"), "Мишта вах хьо?"); // «Где ты живёшь? — Мича вах хьо?»
    assert.ok(!/санна/.test(t3("Как твоя семья?")), t3("Как твоя семья?"));
    assert.strictEqual(t3("Куда ты едешь?"), "Мича вода хьо?"); // «Куда ты идёшь? — Мича вода хьо?»
    // прилагательное-сказуемое — после подлежащего и со связкой: «Мальчик маленький», а не «Маленький мальчик»
    assert.strictEqual(t3("Мальчик маленький"), "КӀаьнк зӀамига ва");
    // «большой»: доккха (справочник), боккха (PaydaDosh), воккха кӀаьнк, йоккха йиӀиг (PaydaDosh) — по классу
    // существительного: цӀа (д/д), дезал (б/б), машен (й/й)
    assert.strictEqual(t3("Большой дом"), "Доккха цӀа");
    assert.strictEqual(t3("Большая семья"), "Боккха дезал");
    assert.strictEqual(t3("Семья большая"), "Дезал боккха ба");
    assert.strictEqual(t3("У меня большая машина"), "Сога йоккха машен я");
    // «хороший — дика» — один класс в словаре: не меняется (справочник: «дика саг», «хоза йоӀ»)
    // и «Это X» — со связкой по классу X (справочник, раздел 4: «Ер са нана я»): книжка (д) — да
    assert.strictEqual(t3("Это хорошая книга"), "Ер дика книжка да");
    // «старый» о человеке-подлежащем — «воккха, йоккха (о людях)» (справочник), о вещах — «къаьна»
    assert.strictEqual(t3("Отец старый"), "Да воккха ва");
    assert.ok(/къаьна/.test(t3("Их дом старый")), t3("Их дом старый"));
    // числа: короткая форма и ед. ч. (раздел 8: «ши саг», «кхо шу»); «дома» после числа — «цӀа», не «цӀагӀа»
    assert.strictEqual(t3("Два брата"), "Ши воша");
    assert.strictEqual(t3("Три года"), "Кхо шу");
    assert.strictEqual(t3("Два дома"), "Ши цӀа"); // PaydaDosh: «два дома — ши цӀа»
    // «четыре» — по классу (PaydaDosh: «виъ новкъост», «йиъ кийла», «биъ Ӏаж»); «ди» — это «день»
    assert.strictEqual(t3("Четыре дочери"), "Йиъ йоӀ");
    assert.strictEqual(t3("Четыре друга"), "Виъ новкъост");
    assert.ok(!/^Ди /.test(t3("Четыре книги")), t3("Четыре книги"));
    // по аналогии — класс связки и прилагательного меняется вместе с существительным; «я дома — со цӀагӀа ва»
    // для «мы»: «тхо … да» (раздел 4: тхо, вай, шо — д)
    assert.strictEqual(t3("Мы дома"), "Тхо цӀагӀа да");
    assert.strictEqual(t3("Это моя мать"), "Ер са нана я");
    // запрет — «ма» (раздел 7: «Ма де!»), «плачь» — повелительное от «плакать», а не «плач»
    assert.strictEqual(t3("Не плачь"), "Ма делха");
    // «хочу есть» — «есть (кушать) — даа» (справочник), не «есть (имеется)»
    assert.ok(/ даа лов$/.test(t3("Он хочет есть")), t3("Он хочет есть"));
    console.log("ok 6и: класс и порядок —", t3("Мать любит детей"), "|", t3("Как вы живёте?"), "|", t3("Большая семья"), "|", t3("Четыре друга"), "|", t3("Мы дома"));

    // 6к. «сказать кому» — направительный на -га (PaydaDosh: «Скажите мне — Ала сога», «Скажи дочери — Ала
    // йоӀага», «Я скажу об этом матери — Аз наьнага дӀааргда из»; справочник, раздел 6: «нанега»)
    assert.ok(/^(Нанега|Наьнага) ала$/.test(t3("Скажи матери")), t3("Скажи матери"));
    assert.ok(/^Сога /.test(t3("Скажи мне правду")), t3("Скажи мне правду"));
    assert.ok(/^Цунга ала$/.test(t3("Скажи ему")), t3("Скажи ему"));
    // прямое дополнение-человек — в именительном (раздел 4), не «даь» (родительный): «Сона хьо веза»
    assert.ok(/ да веза$/.test(t3("Сын любит отца")), t3("Сын любит отца"));
    assert.ok(/ даь /.test(t3("Пусть ты понесешь труп своего отца")), "после существительного — родительный: " + t3("Пусть ты понесешь труп своего отца"));
    // прилагательное перед существительным в косвенном падеже — на -ча (PaydaDosh: «доккхача ор чу»,
    // «воккхача сага», «дикача наькъа тӀа»); «С новым годом» — существительное не изменилось: «керда»
    assert.ok(/ доккхача ишколе /.test(t3("Мальчик идёт в большую школу")), t3("Мальчик идёт в большую школу"));
    assert.ok(/воккхача сага/.test(t3("Дай воды старому человеку")), t3("Дай воды старому человеку"));
    assert.ok(!/кердача/.test(t3("С новым годом")), t3("С новым годом"));
    // «не бойся» — запрет «ма» и возвратное повелительное (PaydaDosh: «Не бойтесь — Ма кхера»)
    assert.strictEqual(t3("Не бойся"), "Ма кхера");
    // «спасибо большое» — прилагательное перед существительным (PaydaDosh: «доккха баркал»); «Работа трудная» — сказуемое
    assert.strictEqual(t3("Спасибо большое"), "Доккха баркал");
    assert.ok(/^Болх хала/.test(t3("Работа трудная")), t3("Работа трудная"));
    // поздравление без «поздравляю» — фраза разговорника (PaydaDosh: «Поздравляю тебя с днём рождения! — Ваьча
    // денза даькъала вувц хьо!»)
    assert.strictEqual(t3("С днём рождения!"), "Ваьча денза даькъала вувц хьо!");
    // образцы-мусор не берём: «выключи свет — свет дӀайоае» для «включи свет», «это удивительно — тамаш йолаш хӀама да»
    assert.ok(!/дӏайоае|дӀайоае/.test(t3("Включи свет")), t3("Включи свет"));
    assert.ok(!/йолаш хӀама/.test(t3("Это дёшево")), t3("Это дёшево"));
    console.log("ok 6к: кому сказать, дополнение, -ча, запрет, фразы целиком —", t3("Скажи матери"), "|", t3("Сын любит отца"), "|", t3("Мальчик идёт в большую школу"), "|", t3("Не бойся"), "|", t3("С днём рождения!"));

    // 6м. «Это X» — связка (справочник, раздел 4: «Ер са нана я»); «это» + наречие-качество — «Из … да»
    // (PaydaDosh: «Это хорошо — Из дика да», «Это правда — Из бакъ да», «Это несправедливо — Из нийса дац»,
    // «Это дорого — Деза да ер»); вопрос — сказуемое, связка, «из» (PaydaDosh: «Это далеко? — Гаьна дий из?»)
    assert.strictEqual(t3("Это дёшево"), "Из дарегӏа да");
    assert.strictEqual(t3("Это не дёшево"), "Из дарегӏа дац");
    assert.strictEqual(t3("Это интересно?"), "Сакъердаме дий из?");
    assert.strictEqual(t3("Это дорого"), "Из деза да"); // «дорого — веза» в классе д, как «Деза да ер»
    assert.strictEqual(t3("Это вкусный хлеб"), "Ер чаме маькх я"); // маькх (й): «Это хлеб — Ер маькх я»
    assert.ok(!/кӏаьнк|кӀаьнк/.test(t3("Дом брата")), t3("Дом брата")); // образец «сын брата — веший воӀ кӀаьнк» не годится
    assert.ok(!/ да$/.test(t3("Дом брата")), t3("Дом брата")); // «брата» — родительный, не сказуемое
    assert.ok(!/ да$/.test(t3("Это просто")), t3("Это просто")); // «просто» — частица, не сказуемое («иштта да» — «это так»)
    // родительный перед существительным (справочник, раздел 8): «Книга отца» — «Даь книжка», без связки
    assert.strictEqual(t3("Книга отца"), "Даь книжка");
    // «ждать» кого — направительный, кто ждёт — именительный (PaydaDosh: «ждать брата — вешийга хьежа»,
    // «Я не буду тебя ждать — Со хьога хьежаргвац», «Я буду вас ждать — Со хьежаргва шуга»)
    assert.strictEqual(t3("Я жду тебя"), "Со хьога хьежа");
    assert.strictEqual(t3("Я жду отца"), "Со даьга хьежа"); // «Отдай это отцу — Даьга дӀале ер» (PaydaDosh)
    assert.strictEqual(t3("Я жду маму"), "Со нанега хьежа"); // «нанега» — справочник, раздел 6
    // «у отца есть» — направительный, как «сога, хьога» (справочник, разделы 3 и 6), связка по классу того, что есть
    assert.strictEqual(t3("У отца есть машина"), "Даьга машен я");
    assert.strictEqual(t3("У отца нет машины"), "Даьга машен яц");
    // «Передай привет …» — по образцу «Передай привет семье — ЦӀагӀарчарга салам-моаршал лелахь» (PaydaDosh)
    assert.strictEqual(t3("Передай привет маме"), "Нанега салам-моаршал лелахь");
    assert.strictEqual(t3("Передай ему привет"), "Цунга салам-моаршал лелахь");
    // «Школа большая» — сказуемое, не «большая школа» (порядок «Спасибо большое → Доккха баркал» — только не для м./ж. рода)
    assert.ok(!/^Доккха школа/.test(t3("Школа большая")), t3("Школа большая"));
    console.log("ok 6м: это X, ждать кого, у кого есть, привет —", t3("Это дёшево"), "|", t3("Я жду отца"), "|", t3("У отца есть машина"), "|", t3("Передай привет маме"));
  }
  // 6з. ингушский → русский: формы глагола, которых нет в словаре целиком (lib/rules/inh-verbs.js).
  // Все предложения — из PaydaDosh (русский перевод носителя в скобках):
  //   будущее «-рг-»: «Со гӀоргвац» (Я не пойду), «Хьо кхоана воагӀаргва?» (по «Со кхоана воагӀаргва» — Я приеду
  //   завтра), «Аз эцаргда из» (Я куплю это), «Сабарде дезаргда» (Придётся подождать);
  //   повелительное «-л», «-лахь»: «КӀеззига сабардел» (Подожди немного), «Сона укхаз сабарделахь» (Подожди меня здесь);
  //   повелительное по-русски — в начале, как у носителя
  //   отрицание настоящего: «Аз дулх дуац» (Я не ем мясо); перфект: «Со цӀаккхаза хиннавац цига» (Я никогда там не был);
  //   «йоал» после причастия и в вопросе: «Нана локъамаш еш йоал» (Мама делает оладьи), «Тика мичахьа йоал?» (Где магазин?)
  assert.strictEqual(tr("Со гӀоргвац.", "inh"), "Я не пойду.");
  assert.ok(/^Ты завтра придешь\?$/.test(tr("Хьо кхоана воагӀаргва?", "inh")), tr("Хьо кхоана воагӀаргва?", "inh"));
  assert.ok(/^Я (возьму|куплю) /.test(tr("Аз эцаргда из.", "inh")), tr("Аз эцаргда из.", "inh"));
  assert.ok(/придется/.test(tr("Сабарде дезаргда.", "inh")), tr("Сабарде дезаргда.", "inh"));
  assert.ok(/(подожди|стоп)/i.test(tr("КӀеззига сабардел.", "inh")), tr("КӀеззига сабардел.", "inh")); // PaydaDosh: «стоп — сабардел»
  assert.ok(/^Подожди /.test(tr("Сона укхаз сабарделахь.", "inh")), tr("Сона укхаз сабарделахь.", "inh"));
  assert.ok(/не ем/.test(tr("Аз дулх дуац.", "inh")), tr("Аз дулх дуац.", "inh"));
  assert.ok(/не был там/.test(tr("Со цӀаккхаза хиннавац цига.", "inh")), tr("Со цӀаккхаза хиннавац цига.", "inh"));
  assert.ok(/делает$/.test(tr("Нана локъамаш еш йоал", "inh")), tr("Нана локъамаш еш йоал", "inh"));
  assert.strictEqual(tr("Тика мичахьа йоал?", "inh"), "Где магазин?");
  // «-ал» не в конце — это сравнение, не повелительное («ДӀаьхача дешал…» — чем длинное слово)
  assert.ok(!/читай/.test(tr("ДӀаьхача дешал лоаца охка тол", "inh")), tr("ДӀаьхача дешал лоаца охка тол", "inh"));
  // русские формы для этого: повелительное и будущее (ru-conj)
  const RUC = require("../lib/rules/ru-conj.js");
  assert.deepStrictEqual(["подождать", "рассказать", "сказать", "делать", "учиться", "быть"].map(RUC.imperative), ["подожди", "расскажи", "скажи", "делай", "учись", "будь"]);
  assert.strictEqual(RUC.future("сделать", 0, true), "сделаю");
  assert.strictEqual(RUC.future("делать", 3, false), "будем делать");
  console.log("ok 6з: формы ингушского глагола —", tr("Со гӀоргвац.", "inh"), "|", tr("КӀеззига сабардел.", "inh"), "|", tr("Аз дулх дуац.", "inh"), "|", tr("Тика мичахьа йоал?", "inh"));

  // 6и. ингушский → русский: падеж русского существительного по окончанию ингушского слова и по роли в
  // предложении (справочник, раздел 6). Все ингушские фразы — из PaydaDosh и справочника.
  // дополнение при подлежащем в эргативе — винительный («Цо машен ийцай» — он купил машину)
  assert.ok(/машину/.test(tr("Цо машен ийцай.", "inh")), tr("Цо машен ийцай.", "inh"));
  assert.ok(/машину/.test(tr("Дас машен ийцай.", "inh")), tr("Дас машен ийцай.", "inh"));
  // «куда»: «на работу», «в школу»; «где»: город — предложный («в Назрани»)
  assert.ok(/на работу/.test(tr("Со балха вода.", "inh")), tr("Со балха вода.", "inh"));
  assert.ok(/в школу/.test(tr("Ишколе вода со.", "inh")), tr("Ишколе вода со.", "inh"));
  assert.ok(/в Назрани/.test(tr("Из Назране вахаш ва.", "inh")), tr("Из Назране вахаш ва.", "inh"));
  // -ца: «с» + творительный, транспорт — «на» («Вай автобусаца гӀоргда» — мы поедем на автобусе)
  assert.ok(/с людьми/i.test(tr("Нахаца хьаьнала хила", "inh")), tr("Нахаца хьаьнала хила", "inh"));
  assert.ok(/на автобусе/.test(tr("Вай автобусаца гӀоргда", "inh")), tr("Вай автобусаца гӀоргда", "inh"));
  // -на: дательный, с определением в том же падеже («Хорошей хозяйке…»)
  assert.ok(/хорошей хозяйке/i.test(tr("Дикача фусамнанна пхьор а дика чам болаш хул.", "inh")), tr("Дикача фусамнанна пхьор а дика чам болаш хул.", "inh"));
  // родительный перед существительным — по-русски после него: «бӀехала когаш» — ноги змеи (PaydaDosh)
  assert.ok(/(ноги змеи|змеиные ноги)/i.test(tr("Зунгата бӀаргаш, бӀехала когаш", "inh")), tr("Зунгата бӀаргаш, бӀехала когаш", "inh"));
  // без глагола и без эргатива падеж не меняется: «Са да лор ва» — мой отец врач
  assert.strictEqual(tr("Са да лор ва", "inh"), "Мой отец врач");
  console.log("ok 6и: падежи ингушский → русский —", tr("Цо машен ийцай.", "inh"), "|", tr("Со балха вода.", "inh"), "|", tr("Вай автобусаца гӀоргда", "inh"));

  // 6к. Ингушский → русский: значения, которые решает контекст. Все пары — PaydaDosh и справочник.
  // «деза»: что нужно — существительное («Сона лор веза» — мне нужен врач), перед ним инфинитив («Ваха веза са» —
  // мне надо идти), кого любят — местоимение («Сона хьо веза»), родные («Нанна воӀ веза»), «дукха» (очень)
  assert.strictEqual(tr("Сона лор веза.", "inh"), "Мне нужен врач.");
  assert.ok(/^Мне нужен /.test(tr("Сона талмач веза", "inh")), tr("Сона талмач веза", "inh"));
  assert.strictEqual(tr("Фу деза шоана?", "inh"), "Что вам нужно?");
  assert.ok(/^Мне надо /.test(tr("Ваха веза са.", "inh")), tr("Ваха веза са.", "inh"));
  assert.strictEqual(tr("Сона хьо веза", "inh"), "Я тебя люблю");
  assert.ok(/любит/.test(tr("Нанна воӀ веза", "inh")), tr("Нанна воӀ веза", "inh"));
  assert.ok(/очень люблю/.test(tr("Сона лоамаш дукха деза", "inh")), tr("Сона лоамаш дукха деза", "inh"));
  // «хоза хет» — нравится: «Сона хоза хетац из» — мне это не нравится, «Сона хьо хозахет» — ты мне нравишься
  assert.strictEqual(tr("Сона хоза хетац из.", "inh"), "Мне это не нравится.");
  assert.strictEqual(tr("Сона хьо хозахет.", "inh"), "Ты мне нравишься.");
  // «Виц ма лелахь» — не забудь
  assert.strictEqual(tr("Виц ма лелахь.", "inh"), "Не забудь.");
  console.log("ok 6к: деза, хоза хет, виц лело —", tr("Сона лор веза.", "inh"), "|", tr("Сона хоза хетац из.", "inh"), "|", tr("Виц ма лелахь.", "inh"));

  // 6л. Множественное число и согласование (справочник, разделы 4, 6, 8; PaydaDosh)
  assert.ok(/^Дети (при|пришли)/.test(tr("Бераш хьадаьхкад.", "inh")) && /ли\.$/.test(tr("Бераш хьадаьхкад.", "inh")), tr("Бераш хьадаьхкад.", "inh")); // дети пришли
  assert.strictEqual(tr("Доккхий цӀенош.", "inh"), "Большие дома.");
  assert.ok(/машины большие/.test(tr("Са машенаш йоккха я.", "inh")), tr("Са машенаш йоккха я.", "inh"));
  assert.ok(/с друзьями/i.test(tr("ДоттагӀашца вӀашагӀкхета", "inh")), tr("ДоттагӀашца вӀашагӀкхета", "inh"));
  assert.strictEqual(tr("Хий дӀайха да.", "inh"), "Вода горячая.");
  assert.strictEqual(tr("Из дика саг ва.", "inh"), "Он хороший человек.");
  assert.strictEqual(tr("Тахан шийла я.", "inh"), "Сегодня холодно.");
  // «наха» — люди (эргатив мн. ч.), не «людей»: «Наха саг магӀа а воаккх»
  assert.ok(/^Люди /.test(tr("Наха саг магӀа а воаккх.", "inh")), tr("Наха саг магӀа а воаккх.", "inh"));
  // «вай» перед существительным без глагола — «наш»; с глаголом — «мы»
  assert.strictEqual(tr("Из вай цӀа да.", "inh"), "Это наш дом.");
  assert.ok(/^Мы /.test(tr("Вай автобусаца гӀоргда", "inh")), tr("Вай автобусаца гӀоргда", "inh"));
  assert.strictEqual(tr("Из кхалсаг я", "inh"), "Она женщина");
  assert.strictEqual(tr("Из студент я.", "inh"), "Она студент."); // по образцу «Со студент я» (PaydaDosh), связка й — она
  console.log("ok 6л: множественное и согласование —", tr("Бераш хьадаьхкад.", "inh"), "|", tr("Доккхий цӀенош.", "inh"), "|", tr("Хий дӀайха да.", "inh"), "|", tr("Из вай цӀа да.", "inh"));

  // 7. сервер: без USE_AI=1 ИИ не вызывается, отвечает перевод по кускам
  let aiCalls = 0;
  global.fetch = async () => { aiCalls++; throw new Error("no network"); };
  process.env.GEMINI_API_KEY = "test"; // ключ есть, но ИИ выключен
  const T = require("../api/translate.js");
  T._setStore({ get: async () => null, setJSON: async () => {} });
  require("../lib/corpus.js")._set({ store: { get: async () => null, setJSON: async () => {} }, fetch: async () => ({ ok: false, status: 404, text: async () => "" }) });
  const call = (body) => new Promise((resolve) => { const res = { code: 200, status(c) { this.code = c; return this; }, json(o) { resolve({ code: this.code, data: o }); } }; T({ method: "POST", body }, res); });
  const s = await call({ text: "Мальчик идёт в большую школу", source: "ru", target: "inh", mode: "text" });
  assert.strictEqual(s.code, 200);
  assert.strictEqual(s.data.chunks, true);
  assert.ok(!s.data.ai, "не ИИ");
  assert.ok(/ вода$/.test(s.data.translation), s.data.translation);
  assert.strictEqual(aiCalls, 0, "к ИИ не обращались");
  // одно ингушское слово — форма глагола из библиотеки слов, а не «бегущий» из словаря
  const v = await call({ text: "вода", source: "inh", target: "ru", mode: "word" });
  assert.ok(/^ид[её]т$/.test(v.data.translation), v.data.translation);
  // утверждение не получает ответ-вопрос из базы: в разговорнике только «Это далеко? — Гаьна дий из?»
  const far = await call({ text: "Это далеко", source: "ru", target: "inh", mode: "text" });
  assert.ok(!/\?$/.test(far.data.translation), far.data.translation);
  const farQ = await call({ text: "Это далеко?", source: "ru", target: "inh", mode: "text" });
  assert.strictEqual(farQ.data.translation, "Гаьна дий из?");
  const how = await call({ text: "Как дела", source: "ru", target: "inh", mode: "text" });
  assert.ok(/\?$/.test(how.data.translation), how.data.translation); // с вопросительным словом — вопрос и без знака
  console.log(`ok 7: сервер без ИИ → «${s.data.translation}» [${s.data.model}]`);

  console.log("\nВсе проверки перевода по кускам прошли.");
  process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
